import "server-only";
import { createClient } from "@/lib/supabase/server";
import type { AdminProduct, ProductInput } from "@/lib/products";
import { removeCatalogImages } from "./storage";

export type Result = { ok: true } | { ok: false; error: string };
const fail = (error: string): Result => ({ ok: false, error });

type ImageRow = {
  image_url: string;
  product_images: { image_url: string }[] | null;
};
type Row = ImageRow & {
  id: number;
  name: string;
  description: string;
  category: string;
  price: number | string;
  discount_percent: number | string;
  sale_price: number | string;
  stock: number;
  color: string;
  extra_info: Record<string, string> | null;
  product_images: { image_url: string; sort_order: number }[] | null;
};

const SELECT =
  "id, name, description, category, price, discount_percent, sale_price, stock, color, image_url, extra_info, product_images(image_url, sort_order)";

const urlsOf = (row: ImageRow) => [
  row.image_url,
  ...(row.product_images ?? []).map((i) => i.image_url),
];

const toAdmin = (r: Row): AdminProduct => ({
  id: r.id,
  name: r.name,
  description: r.description,
  category: r.category,
  price: Number(r.price),
  discountPercent: Number(r.discount_percent),
  salePrice: Number(r.sale_price),
  stock: r.stock,
  color: r.color,
  image: r.image_url,
  images: [...(r.product_images ?? [])]
    .sort((a, b) => a.sort_order - b.sort_order)
    .map((i) => i.image_url),
  extraInfo: r.extra_info ?? {},
});

export async function listAdminProducts(): Promise<AdminProduct[]> {
  const supabase = await createClient();
  const { data, error } = await supabase
    .from("products")
    .select(SELECT)
    .order("id", { ascending: false }) // newest first
    .limit(1000);
  if (error) throw new Error("Could not load products.");
  return (data as unknown as Row[]).map(toAdmin);
}

export async function saveProductRecord(
  id: number | null,
  input: ProductInput,
): Promise<Result> {
  const supabase = await createClient();
  // sale_price is generated by the database from price + discount_percent
  const row = {
    name: input.name,
    description: input.description,
    category: input.category,
    price: Math.round(input.price * 100) / 100,
    discount_percent: Math.round(input.discountPercent * 100) / 100,
    stock: input.stock,
    color: input.color,
    image_url: input.image,
    extra_info: input.extraInfo,
  };

  let productId = id;
  let oldUrls: string[] = [];

  if (id === null) {
    const { data, error } = await supabase
      .from("products")
      .insert(row)
      .select("id")
      .single();
    if (error || !data) {
      console.error("[saveProductRecord:insert]", error?.code, error?.message);
      return fail("Could not save the product.");
    }
    productId = data.id as number;
  } else {
    const { data: existing } = await supabase
      .from("products")
      .select("image_url, product_images(image_url)")
      .eq("id", id)
      .maybeSingle();
    if (!existing) return fail("Product not found.");
    oldUrls = urlsOf(existing as unknown as ImageRow);

    const { error } = await supabase.from("products").update(row).eq("id", id);
    if (error) {
      console.error("[saveProductRecord:update]", error.code, error.message);
      return fail("Could not save the product.");
    }
  }

  const { error: galleryError } = await supabase.rpc("replace_product_images", {
    p_product_id: productId,
    p_urls: input.images,
  });
  if (galleryError) {
    console.error("[saveProductRecord:gallery]", galleryError.message);
    return fail("Saved, but the extra photos could not be updated. Try again.");
  }

  // Delete photos that were removed or replaced
  const kept = new Set([input.image, ...input.images]);
  await removeCatalogImages(oldUrls.filter((u) => !kept.has(u)));
  return { ok: true };
}

export async function deleteProductRecord(id: number): Promise<Result> {
  const supabase = await createClient();
  const { data: existing } = await supabase
    .from("products")
    .select("image_url, product_images(image_url)")
    .eq("id", id)
    .maybeSingle();

  const { error } = await supabase.from("products").delete().eq("id", id);
  if (error) {
    console.error("[deleteProductRecord]", error.code, error.message);
    return fail("Could not delete the product.");
  }
  if (existing)
    await removeCatalogImages(urlsOf(existing as unknown as ImageRow));
  return { ok: true };
}

export async function setProductStockRecord(
  id: number,
  stock: number,
): Promise<Result> {
  const supabase = await createClient();
  const { error } = await supabase
    .from("products")
    .update({ stock })
    .eq("id", id);
  if (error) {
    console.error("[setProductStockRecord]", error.code, error.message);
    return fail("Could not update the stock.");
  }
  return { ok: true };
}
